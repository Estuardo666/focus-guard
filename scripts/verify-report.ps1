$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

$requiredReportSections = @(
    "## 1. Executive summary",
    "## 2. Final validation",
    "## 3. Completed milestones",
    "## 4. Incomplete milestones",
    "## 6. Commits",
    "## 10. Pending risks",
    "## 11. Deliberately unexecuted for safety"
)

foreach ($path in @("OVERNIGHT_PROGRESS.md", "OVERNIGHT_REPORT.md")) {
    if (-not (Test-Path $path)) {
        throw "Required report file is missing: $path"
    }
}

$report = Get-Content -Raw OVERNIGHT_REPORT.md
foreach ($section in $requiredReportSections) {
    if (-not $report.Contains($section)) {
        throw "Required report section is missing: $section"
    }
}

$artifactDirectory = Join-Path (Get-Location) "artifacts"
New-Item -ItemType Directory -Force -Path $artifactDirectory | Out-Null
$validationPath = Join-Path $artifactDirectory "overnight-validation.md"
@(
    "# FocusGuard validation artifact",
    "",
    "- Report structure: passed",
    "- Progress log present: passed",
    "- Generated by: scripts/verify-report.ps1",
    "- Generated at: $(Get-Date -Format o)"
) | Set-Content -Encoding utf8 $validationPath
Write-Host "Report validation passed: $validationPath"
